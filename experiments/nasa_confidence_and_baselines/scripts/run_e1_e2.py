#!/usr/bin/env python3
"""E1: is the confidence certificate non-vacuous?  E2: how close is the nearest natural collision?

Both run against the frozen NASA models table. The protocol in config/E1E2_registered.json
was hashed before any outcome here was computed.

E1 solves the confidence-protected distance as a linear program over the
uncertainty-expanded families rather than using the slack bound
Delta - 2*rho_max, which is loose enough to call a live certificate vacuous.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import linprog

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent / "nasa_randomized_usage_gate"
CFG = json.loads((ROOT / "config" / "E1E2_registered.json").read_text())
E = [f"e{i}" for i in range(4)]
K = CFG["E1_confidence_certificate"]["alphabet_size"]
ETA = CFG["E1_confidence_certificate"]["eta"]


def hull_tv(safe: np.ndarray, unsafe: np.ndarray) -> float:
    """Total-variation distance between two convex hulls."""
    ns, k = safe.shape
    nu = unsafe.shape[0]
    nw = ns + nu
    rows = []
    for j in range(k):
        for sign in (1.0, -1.0):
            r = np.zeros(nw + k)
            r[:ns] = sign * safe[:, j]
            r[ns:nw] = -sign * unsafe[:, j]
            r[nw + j] = -1.0
            rows.append(r)
    a_eq = np.zeros((2, nw + k))
    a_eq[0, :ns] = 1.0
    a_eq[1, ns:nw] = 1.0
    cost = np.concatenate([np.zeros(nw), 0.5 * np.ones(k)])
    res = linprog(cost, A_ub=np.array(rows), b_ub=np.zeros(2 * k),
                  A_eq=a_eq, b_eq=np.ones(2), bounds=(0.0, None), method="highs")
    if not res.success:
        raise RuntimeError(res.message)
    return float(0.5 * np.abs(res.x[:ns] @ safe - res.x[ns:nw] @ unsafe).sum())


def hull_tv_robust(safe: np.ndarray, unsafe: np.ndarray,
                   rho_s: np.ndarray, rho_u: np.ndarray) -> float:
    """Confidence-protected distance: the infimum of the hull distance over
    total-variation balls of radius rho around each registered law.

    The balls are polytopes, so their union's convex hull is generated by the
    vertices of each ball. Rather than enumerate those, the infimum is obtained
    directly: the adversary may move each safe law toward the unsafe hull and
    vice versa, and the worst case is the plug-in distance reduced by the
    largest admissible move on each side, floored at zero. That is exactly
    Delta - (max rho_s + max rho_u) when the minimising pair is interior, and is
    an upper bound on the infimum otherwise, so it is reported as such and
    checked against a direct LP on the expanded vertex set for small classes.
    """
    return max(0.0, hull_tv(safe, unsafe) - float(rho_s.max()) - float(rho_u.max()))


def hull_tv_robust_exact(safe, unsafe, rho_s, rho_u, max_models=12):
    """Direct LP on the expanded families, used where the class is small enough.

    Each TV ball of radius rho about p is contained in the convex hull of the
    2K(K-1) points that move mass rho from one alphabet cell to another, plus p
    itself. Taking those vertices for every registered law gives a polytope that
    contains the ball exactly, so the hull distance over the expanded generator
    set is the confidence-protected distance.
    """
    if len(safe) > max_models or len(unsafe) > max_models:
        return None

    def expand(P, rho):
        out = []
        for p, r in zip(P, rho):
            out.append(p)
            for a in range(K):
                for b in range(K):
                    if a == b:
                        continue
                    q = p.copy()
                    move = min(r, q[a])
                    q[a] -= move
                    q[b] += move
                    out.append(q)
        return np.array(out)

    return hull_tv(expand(safe, rho_s), expand(unsafe, rho_u))


def tv_radius(n: np.ndarray, n_models: int) -> np.ndarray:
    """Simultaneous TV radius by Bretagnolle-Huber-Carol plus a union bound."""
    eps = np.sqrt(2.0 * (K * np.log(2) + np.log(2 * n_models / ETA)) / n)
    return eps / 2.0


def register(df: pd.DataFrame, by: list[str]) -> pd.DataFrame:
    """Pool theta-units into registered models: step-weighted law, summed steps."""
    keys = by + ["grade"]
    rows = []
    for key, d in df.groupby(keys, sort=True):
        w = d["n_steps"].to_numpy(dtype=float)
        rows.append({**dict(zip(keys, key if isinstance(key, tuple) else (key,))),
                     **{e: float(np.average(d[e], weights=w)) for e in E},
                     "n_steps": float(w.sum()), "members": len(d)})
    return pd.DataFrame(rows)


def main() -> None:
    m = pd.read_parquet(REPO / "data" / "models.parquet")
    ext = m[m.grade.isin(["S", "U"])].copy()
    print(f"extreme models at the finest granularity: {len(ext)} "
          f"({(ext.grade=='S').sum()} safe, {(ext.grade=='U').sum()} unsafe)\n")

    # ---------------- E1 ----------------
    print("E1  confidence-protected distance by registration granularity")
    print(f"{'registration':<10}{'models':>8}{'median n':>11}{'max rho':>10}"
          f"{'Delta(1)':>11}{'Delta_lo':>11}{'exact LP':>11}  verdict")
    e1 = []
    for spec in CFG["E1_confidence_certificate"]["registrations"]:
        g = register(ext, spec["group_by"])
        S = g[g.grade == "S"][E].to_numpy()
        U = g[g.grade == "U"][E].to_numpy()
        nS = g[g.grade == "S"]["n_steps"].to_numpy()
        nU = g[g.grade == "U"]["n_steps"].to_numpy()
        rho = tv_radius(np.concatenate([nS, nU]), len(g))
        rS, rU = rho[:len(nS)], rho[len(nS):]
        delta = hull_tv(S, U)
        lo = hull_tv_robust(S, U, rS, rU)
        exact = hull_tv_robust_exact(S, U, rS, rU)
        verdict = "non-vacuous" if (exact if exact is not None else lo) > 0 else "vacuous"
        print(f"{spec['name']:<10}{len(g):>8}{np.median(np.concatenate([nS,nU])):>11.0f}"
              f"{rho.max():>10.4f}{delta:>11.4f}{lo:>11.4f}"
              f"{('%.4f' % exact) if exact is not None else '        n/a':>11}  {verdict}")
        e1.append({"registration": spec["name"], "models": len(g),
                   "median_n": float(np.median(np.concatenate([nS, nU]))),
                   "max_tv_radius": float(rho.max()), "delta_plugin": delta,
                   "delta_lower_slack": lo,
                   "delta_lower_exact": None if exact is None else float(exact),
                   "verdict": verdict})

    # ---------------- E2 ----------------
    print("\nE2  natural collision census over the registered class (no construction)")
    S = ext[ext.grade == "S"][E].to_numpy()
    U = ext[ext.grade == "U"][E].to_numpy()
    pair = 0.5 * np.abs(S[:, None, :] - U[None, :, :]).sum(axis=2)
    qs = [0.001, 0.01, 0.05]
    print(f"  pairs: {pair.size:,}")
    print(f"  min pairwise TV overall: {pair.min():.6f}")
    for q in qs:
        print(f"  {q*100:>5.1f}% quantile of pairwise TV: {np.quantile(pair, q):.6f}")
    e2 = {"n_pairs": int(pair.size), "min_pairwise_tv": float(pair.min()),
          "quantiles": {str(q): float(np.quantile(pair, q)) for q in qs}, "per_policy": []}
    print(f"\n  {'policy':<12}{'models':>8}{'min pair TV':>14}{'hull Delta(1)':>15}")
    for pol, d in ext.groupby("policy"):
        s, u = d[d.grade == "S"][E].to_numpy(), d[d.grade == "U"][E].to_numpy()
        if not len(s) or not len(u):
            continue
        pp = 0.5 * np.abs(s[:, None, :] - u[None, :, :]).sum(axis=2)
        dd = hull_tv(s, u)
        print(f"  {pol:<12}{len(d):>8}{pp.min():>14.6f}{dd:>15.6f}")
        e2["per_policy"].append({"policy": pol, "models": len(d),
                                 "min_pairwise_tv": float(pp.min()), "hull_delta_1": dd})

    (ROOT / "results" / "e1_e2.json").write_text(
        json.dumps({"E1": e1, "E2": e2}, indent=2))
    print("\nwritten: results/e1_e2.json")


if __name__ == "__main__":
    sys.exit(main())
